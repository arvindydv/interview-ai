// Builds the unpacked extension in dist/ (load it from chrome://extensions with "Load unpacked"), and
// dist.zip for the Chrome Web Store. URLs come from the environment, defaulting to local development:
//
//   FRIDAY_API_URL=https://api.example.com FRIDAY_JOBS_URL=https://jobs.example.com pnpm --filter @parakeet/extension build
//
// FRIDAY_OUT (default dist) and FRIDAY_GAP_MS ("lo,hi" ms between applications) are for test builds.

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const config = {
  apiUrl: process.env.FRIDAY_API_URL ?? 'http://localhost:4000',
  jobsUrl: process.env.FRIDAY_JOBS_URL ?? 'http://localhost:3300',
  ...(process.env.FRIDAY_GAP_MS ? { gapMs: process.env.FRIDAY_GAP_MS.split(',').map(Number) } : {}),
};
const out = process.env.FRIDAY_OUT ?? 'dist';

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync('src', out, { recursive: true });
writeFileSync(`${out}/config.js`, `// Generated by build.mjs.\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`);

// The API and jobs site are only known at build time.
const manifest = JSON.parse(readFileSync('src/manifest.json', 'utf8'));
const origin = (u) => `${new URL(u).origin}/*`;
manifest.host_permissions = [...new Set([...manifest.host_permissions, origin(config.apiUrl), origin(config.jobsUrl)])];
manifest.content_scripts[0].matches = [origin(config.jobsUrl)];
writeFileSync(`${out}/manifest.json`, JSON.stringify(manifest, null, 2));

if (out === 'dist') {
  rmSync('dist.zip', { force: true });
  try {
    execFileSync('zip', ['-qr', '../dist.zip', '.'], { cwd: 'dist' });
  } catch {
    console.warn('zip not found; skipped dist.zip');
  }
}
console.log('Built dist/ for', config.apiUrl);
