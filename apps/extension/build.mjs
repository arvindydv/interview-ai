// Builds the unpacked extension in dist/ (load it from chrome://extensions with "Load unpacked"), and
// dist.zip for the Chrome Web Store. URLs come from the environment, defaulting to local development:
//
//   FRIDAY_API_URL=https://api.example.com FRIDAY_JOBS_URL=https://jobs.example.com \
//   FRIDAY_SUPABASE_URL=https://xyz.supabase.co FRIDAY_SUPABASE_KEY=sb_publishable_… pnpm --filter @parakeet/extension build

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const config = {
  apiUrl: process.env.FRIDAY_API_URL ?? 'http://localhost:4000',
  jobsUrl: process.env.FRIDAY_JOBS_URL ?? 'http://localhost:3300',
  supabaseUrl: process.env.FRIDAY_SUPABASE_URL ?? 'http://127.0.0.1:54321',
  supabaseKey: process.env.FRIDAY_SUPABASE_KEY ?? 'sb_publishable_ACJWlzQHlZjBrEguHvfOxg_3BJgxAaH',
};

rmSync('dist', { recursive: true, force: true });
mkdirSync('dist');
cpSync('src', 'dist', { recursive: true });
writeFileSync('dist/config.js', `// Generated by build.mjs.\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`);

// The API and jobs site are only known at build time.
const manifest = JSON.parse(readFileSync('src/manifest.json', 'utf8'));
const origin = (u) => `${new URL(u).origin}/*`;
manifest.host_permissions = [...new Set([...manifest.host_permissions, origin(config.apiUrl), origin(config.supabaseUrl), origin(config.jobsUrl)])];
manifest.content_scripts[0].matches = [origin(config.jobsUrl)];
writeFileSync('dist/manifest.json', JSON.stringify(manifest, null, 2));

rmSync('dist.zip', { force: true });
try {
  execFileSync('zip', ['-qr', '../dist.zip', '.'], { cwd: 'dist' });
} catch {
  console.warn('zip not found; skipped dist.zip');
}
console.log('Built dist/ for', config.apiUrl);
