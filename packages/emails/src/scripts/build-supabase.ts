// Compiles the auth templates to supabase/templates/*.html (with Go placeholders) and regenerates the
// matching [auth.email.template.*] blocks in supabase/config.toml between the generated markers.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createElement } from 'react';
import { render } from 'react-email';
import { supabaseTemplates } from '../templates/auth.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../../..');
const outDir = join(root, 'supabase/templates');
const configPath = join(root, 'supabase/config.toml');
const START = '# >>> auth email templates (generated by packages/emails: pnpm --filter @parakeet/emails build)';
const END = '# <<< auth email templates';

mkdirSync(outDir, { recursive: true });
const blocks: string[] = [];
for (const [key, { component, subject }] of Object.entries(supabaseTemplates)) {
  const html = await render(createElement(component, {}));
  writeFileSync(join(outDir, `${key}.html`), html);
  blocks.push(`[auth.email.template.${key}]\nsubject = ${JSON.stringify(subject)}\ncontent_path = "./supabase/templates/${key}.html"`);
  console.log(`wrote supabase/templates/${key}.html`);
}

const config = readFileSync(configPath, 'utf8');
const generated = `${START}\n${blocks.join('\n\n')}\n${END}`;
const start = config.indexOf(START);
const end = config.indexOf(END);
if (start === -1 || end === -1) throw new Error(`Markers not found in supabase/config.toml; add:\n${START}\n${END}`);
writeFileSync(configPath, config.slice(0, start) + generated + config.slice(end + END.length));
console.log('updated supabase/config.toml template blocks');
