#!/usr/bin/env node
// Refreshes apps/api/src/data/disposableDomains.ts from the community-maintained blocklist
// (https://github.com/disposable-email-domains/disposable-email-domains). Run now and then:
//   node scripts/update-disposable-domains.mjs
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const OUT = new URL('../apps/api/src/data/disposableDomains.ts', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
const domains = [...new Set((await res.text()).split('\n').map((d) => d.trim().toLowerCase()).filter((d) => d && !d.startsWith('#')))].sort();
if (domains.length < 1000) throw new Error(`Only ${domains.length} domains; refusing to overwrite the list`);

writeFileSync(
  OUT,
  `// Generated by scripts/update-disposable-domains.mjs from ${SOURCE}
// on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.

/** Temporary-inbox email domains (${domains.length}), one per line. */
export const DISPOSABLE_DOMAINS = \`
${domains.join('\n')}
\`;
`,
);
console.log(`Wrote ${domains.length} domains to ${OUT.pathname}`);
